uint32_t byteSwap(uint32_t value)
{
    return ((value & 0x000000ffu) << 24) |
           ((value & 0x0000ff00u) << 8) |
           ((value & 0x00ff0000u) >> 8) |
           ((value & 0xff000000u) >> 24);
}

void setBit(std::array<uint8_t, 8> &data, size_t bit, bool value)
{
    const size_t byte = bit / 8 + 1;
    const uint8_t mask = static_cast<uint8_t>(1u << (7u - bit % 8u));
    if (value)
        data[byte] |= mask;
    else
        data[byte] &= static_cast<uint8_t>(~mask);
}

void setBitRange(std::array<uint8_t, 8> &data, size_t start, size_t bits,
                 uint32_t value)
{
    for (size_t i = 0; i < bits; ++i)
        setBit(data, start + i, (value & (uint32_t(1) << (bits - 1 - i))) != 0);
}

bool getBit(const std::array<uint8_t, 8> &data, size_t bit)
{
    return (data[bit / 8 + 1] & (uint8_t(1u << (7u - bit % 8u)))) != 0;
}

void transformBlock(uint8_t *block, const DataKey &dataKey, int direction)
{
    BF_KEY schedule{};
    BF_set_key(&schedule, static_cast<int>(dataKey.key.size()), dataKey.key.data());

    std::array<uint8_t, 8> input{};
    std::array<uint8_t, 8> output{};
    for (size_t half = 0; half < 2; ++half)
        for (size_t byte = 0; byte < 4; ++byte)
            input[half * 4 + byte] = block[half * 4 + 3 - byte];

    BF_ecb_encrypt(input.data(), output.data(), &schedule, direction);

    for (size_t half = 0; half < 2; ++half)
        for (size_t byte = 0; byte < 4; ++byte)
            block[half * 4 + byte] = output[half * 4 + 3 - byte];
}

const DataKey *findDataKey(const uint8_t *header, uint8_t *keyNumber)
{
    for (uint8_t i = 0; i < DataKeys.size(); ++i)
    {
        if (std::memcmp(header + 2, DataKeys[i].name, 6) == 0)
        {
            if (keyNumber)
                *keyNumber = i;
            return &DataKeys[i];
        }
    }
    return nullptr;
}

std::array<uint8_t, 8> addBigEndianBytes(const std::array<uint8_t, 8> &left,
                                         uint64_t right)
{
    std::array<uint8_t, 8> rightBytes{};
    std::memcpy(rightBytes.data(), &right, rightBytes.size());

    std::array<uint8_t, 8> result{};
    unsigned carry = 0;
    for (int i = 7; i >= 0; --i)
    {
        const unsigned sum = left[static_cast<size_t>(i)] +
                              rightBytes[static_cast<size_t>(i)] + carry;
        result[static_cast<size_t>(i)] = static_cast<uint8_t>(sum);
        carry = sum >> 8;
    }
    return result;
}

bool writeDecimal17(const std::array<uint8_t, 8> &value, char *output)
{
    std::array<uint8_t, 8> work = value;
    std::array<char, 32> reversed{};
    size_t count = 0;

    while (count < reversed.size())
    {
        unsigned remainder = 0;
        bool nonzero = false;
        for (uint8_t &byte : work)
        {
            const unsigned dividend = (remainder << 8) + byte;
            byte = static_cast<uint8_t>(dividend / 10);
            remainder = dividend % 10;
            nonzero |= byte != 0;
        }
        if (!nonzero && remainder == 0)
            break;
        reversed[count++] = static_cast<char>('0' + remainder);
    }

    if (count > 17)
        return false;
    while (count < 17)
        reversed[count++] = '0';

    for (size_t i = 0; i < 17; ++i)
        output[i] = reversed[16 - i];
    return true;
}

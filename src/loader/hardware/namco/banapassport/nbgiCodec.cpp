bool decodeHeader(const uint8_t *header, size_t size, DecodedHeader *decoded)
{
    if (!header || size < HeaderSize || !decoded)
        return false;

    if (header[0] != 0x00 || header[1] != 0x02)
        return false;

    uint8_t keyNumber = 0;
    const DataKey *dataKey = findDataKey(header, &keyNumber);
    if (!dataKey)
        return false;

    std::array<uint8_t, 8> payload{};
    std::memcpy(payload.data(), header + 8, payload.size());
    transformBlock(payload.data(), *dataKey, BF_DECRYPT);

    uint8_t checksum = 0;
    for (size_t i = 0; i < 7; ++i)
        checksum ^= payload[i];
    if (checksum != payload[7])
        return false;

    decoded->serial = static_cast<uint32_t>(payload[0]) |
                      (static_cast<uint32_t>(payload[1]) << 8) |
                      (static_cast<uint32_t>(payload[2]) << 16) |
                      (static_cast<uint32_t>(payload[3]) << 24);
    decoded->unknown = static_cast<uint16_t>(payload[4]) |
                       (static_cast<uint16_t>(payload[5]) << 8);
    decoded->flags = payload[6];
    decoded->keyNumber = keyNumber;
    return true;
}

bool encodeHeader(uint8_t keyNumber, uint32_t serial, uint16_t unknown, uint8_t flags,
                  uint8_t *header, size_t size)
{
    if (!header || size < HeaderSize || keyNumber >= DataKeys.size())
        return false;

    std::memset(header, 0, HeaderSize);
    header[0] = static_cast<uint8_t>(HeaderVersion);
    header[1] = static_cast<uint8_t>(HeaderVersion >> 8);
    std::memcpy(header + 2, DataKeys[keyNumber].name, 6);

    std::array<uint8_t, 8> payload = {
        static_cast<uint8_t>(serial),
        static_cast<uint8_t>(serial >> 8),
        static_cast<uint8_t>(serial >> 16),
        static_cast<uint8_t>(serial >> 24),
        static_cast<uint8_t>(unknown),
        static_cast<uint8_t>(unknown >> 8),
        flags,
        0
    };
    for (size_t i = 0; i < 7; ++i)
        payload[7] ^= payload[i];

    transformBlock(payload.data(), DataKeys[keyNumber], BF_ENCRYPT);
    std::memcpy(header + 8, payload.data(), payload.size());
    return true;
}

bool encodeAccessCode(uint8_t keyNumber, uint32_t serial, char *accessCode, size_t size)
{
    if (!accessCode || size < AccessCodeSize + 1 || keyNumber >= AccessKeys.size())
        return false;

    const AccessKey &key = AccessKeys[keyNumber];
    uint32_t product = 300 + keyNumber;
    if (keyNumber == 1)
        product = 302;
    else if (keyNumber == 2)
        product = 303;
    else if (keyNumber == 3)
        product = 304;
    else if (keyNumber == 4)
        product = 305;
    else if (keyNumber == 5)
        product = 306;
    else if (keyNumber == 6)
        product = 307;
    else if (keyNumber == 7)
        product = 308;

    uint32_t appData = 0;
    uint8_t bcc = 0;
    for (size_t i = 0; i < 4; ++i)
    {
        bcc ^= static_cast<uint8_t>(product >> (i * 8));
        bcc ^= static_cast<uint8_t>(serial >> (i * 8));
    }

    product = ((product & 3u) << 8) | (product >> 2);

    std::array<uint8_t, 8> data{};
    setBitRange(data, 0, 2, (bcc % 11) & 3);
    setBitRange(data, 2, 10, product);
    setBitRange(data, 12, 4, appData);
    setBitRange(data, 16, 32, byteSwap(serial));
    setBitRange(data, 48, 8, bcc);

    std::array<uint8_t, 8> temp{};
    for (size_t i = 0; i < BlowfishKeySize; ++i)
    {
        if (getBit(data, i))
            setBit(temp, key.permutation[i] % BlowfishKeySize, true);
    }

    const std::array<uint8_t, 8> result = addBigEndianBytes(temp, key.numericKey);
    std::memcpy(accessCode, key.prefix, 3);
    if (!writeDecimal17(result, accessCode + 3))
        return false;
    accessCode[AccessCodeSize] = '\0';
    return true;
}
